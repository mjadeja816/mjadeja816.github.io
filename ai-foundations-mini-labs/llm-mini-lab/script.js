function updateStation(nextStation) {
  const boundedStation = Math.max(0, Math.min(stations.length - 1, nextStation));
  currentStation = boundedStation;
  highestUnlocked = Math.max(highestUnlocked, currentStation);

  stations.forEach((station, index) => {
    station.classList.toggle("is-active", index === currentStation);
    station.setAttribute("aria-hidden", String(index !== currentStation));
  });

  elements.stationRail.querySelectorAll(".station-tab").forEach((tab, index) => {
    tab.classList.toggle("is-active", index === currentStation);
    tab.classList.toggle("is-complete", index < highestUnlocked);
    tab.disabled = index > highestUnlocked + 1;
  });

  elements.prevButton.disabled = currentStation === 0;
  elements.nextButton.disabled = currentStation === stations.length - 1;
  elements.progressBar.style.width = `${(currentStation / (stations.length - 1)) * 100}%`;
  window.scrollTo({ top: 0, behavior: "smooth" });
}

function restartLab() {
  stopAutoWalkthrough();
  stopGenerationAuto();
  highestUnlocked = 0;
  elements.tokenInput.value = tokenExamples.default;
  elements.rawText.textContent = tokenExamples.default;
  elements.hallucinationDemo.hidden = true;
  resetPrediction();
  resetGeneration();
  tokenizeCurrentSentence(false);
  updateStation(0);
}

function toggleAutoWalkthrough() {
  if (autoTimer) {
    stopAutoWalkthrough();
    return;
  }

  elements.autoButton.setAttribute("aria-pressed", "true");
  elements.autoButton.querySelector("span:last-child").textContent = "Pause";
  autoTimer = window.setInterval(() => {
    if (currentStation >= stations.length - 1) {
      stopAutoWalkthrough();
      return;
    }
    updateStation(currentStation + 1);
  }, 5200);
}

function stopAutoWalkthrough() {
  if (autoTimer) {
    window.clearInterval(autoTimer);
    autoTimer = null;
  }
  elements.autoButton.setAttribute("aria-pressed", "false");
  elements.autoButton.querySelector("span:last-child").textContent = "Auto Walkthrough";
}

function toggleTerms() {
  const isOpen = elements.termsToggle.getAttribute("aria-expanded") === "true";
  if (isOpen) {
    closeTerms();
  } else {
    elements.termsPanel.hidden = false;
    elements.termsToggle.setAttribute("aria-expanded", "true");
  }
}

function closeTerms() {
  elements.termsPanel.hidden = true;
  elements.termsToggle.setAttribute("aria-expanded", "false");
}

function tokenizeCurrentSentence(animate) {
  const text = elements.tokenInput.value.trim() || tokenExamples.default;
  const tokens = tokenize(text);
  elements.rawText.textContent = text;
  elements.tokenOutput.innerHTML = tokens
    .map((token, index) => `<span class="token-pill" style="animation-delay:${animate ? index * 45 : 0}ms">${escapeHtml(token)}</span>`)
    .join("");
  elements.tokenNote.textContent = `${tokens.length} tokens are now visible. The model receives this ordered sequence.`;
}

function tokenize(text) {
  const roughPieces = text.match(/[A-Za-z]+|[0-9]+|[^\sA-Za-z0-9]/g) || [];
  return roughPieces.flatMap(piece => {
    if (/^[A-Za-z]{11,}$/.test(piece)) {
      const midpoint = Math.ceil(piece.length / 2);
      return [piece.slice(0, midpoint), piece.slice(midpoint)];
    }
    return [piece];
  });
}

function renderContextPresets() {
  elements.contextPresets.innerHTML = contextPresets
    .map((preset, index) => `<button type="button" data-context="${index}">${preset.label}</button>`)
    .join("");

  elements.contextPresets.querySelectorAll("[data-context]").forEach(button => {
    button.addEventListener("click", () => {
      selectedContext = contextPresets[Number(button.dataset.context)];
      renderContextTray();
      renderNetworkTokens();
      resetPrediction();
      resetGeneration();
    });
  });
}

function renderContextTray() {
  const capacity = Number(elements.capacitySlider.value);
  const tokens = tokenize(selectedContext.text);
  const visible = tokens.slice(-capacity);
  const hiddenCount = Math.max(0, tokens.length - visible.length);

  elements.capacityValue.textContent = String(capacity);
  elements.contextCount.textContent = `${tokens.length} token${tokens.length === 1 ? "" : "s"}`;
  elements.contextTray.innerHTML = [
    ...Array.from({ length: hiddenCount }, (_, index) => `<span class="token-pill is-muted">older ${index + 1}</span>`),
    ...visible.map(token => `<span class="token-pill">${escapeHtml(token)}</span>`)
  ].join("");

  elements.contextPresets.querySelectorAll("[data-context]").forEach((button, index) => {
    button.classList.toggle("is-selected", contextPresets[index] === selectedContext);
  });

  const insight = document.querySelector(".insight-box span");
  insight.textContent = selectedContext.note;
}

function renderNetworkTokens() {
  const visibleTokens = tokenize(selectedContext.text).slice(-4);
  elements.networkTokens.innerHTML = visibleTokens
    .map(token => `<span class="token-pill">${escapeHtml(token)}</span>`)
    .join("");
}

function processNetwork() {
  elements.networkPanel.classList.add("is-processing");
  elements.networkSignal.textContent = "Processing";
  elements.processButton.disabled = true;

  window.setTimeout(() => {
    elements.networkPanel.classList.remove("is-processing");
    elements.networkSignal.textContent = "Next token scores ready";
    elements.processButton.disabled = false;
  }, 1350);
}

function renderProbabilities() {
  const temperature = Number(elements.temperatureSlider.value);
  const labels = ["Low", "Medium", "Higher"];
  const probabilities = selectedContext.probabilitySets[temperature];
  elements.predictionContext.textContent = selectedContext.text;
  elements.temperatureValue.textContent = labels[temperature];
  elements.probabilityList.innerHTML = probabilities
    .map(([token, value]) => probabilityRow(token, value))
    .join("");
  elements.selectedToken.hidden = true;
  selectedNextToken = null;
}

function sampleNextToken() {
  const temperature = Number(elements.temperatureSlider.value);
  const selected = selectedContext.probabilitySets[temperature][0][0];
  selectedNextToken = selected;
  elements.selectedToken.hidden = false;
  elements.selectedToken.querySelector("strong").textContent = selected;

  elements.probabilityList.querySelectorAll(".probability-row").forEach(row => {
    row.classList.toggle("is-selected", row.dataset.token === selected);
  });
}

function resetPrediction() {
  elements.temperatureSlider.value = "0";
  renderProbabilities();
}

function stepGeneration() {
  if (generationIndex >= selectedContext.generationTokens.length) {
    return;
  }
  generationIndex += 1;
  renderGeneration();
}

function renderGeneration() {
  const nextToken = selectedNextToken || selectedContext.probabilitySets[0][0][0];
  const continuationTokens = selectedContext.generationTokens[0] === nextToken
    ? selectedContext.generationTokens.slice(1)
    : selectedContext.generationTokens;
  const visibleTokens = [
    ...tokenize(selectedContext.text),
    ...(generationIndex > 0 ? [nextToken, ...continuationTokens.slice(0, generationIndex - 1)] : [])
  ];
  elements.generatedText.textContent = visibleTokens.join(" ");
  elements.generationContext.innerHTML = visibleTokens
    .map(token => `<span class="token-pill">${escapeHtml(token)}</span>`)
    .join("");
  elements.stepGenerateButton.disabled = generationIndex >= selectedContext.generationTokens.length;
}

function resetGeneration() {
  stopGenerationAuto();
  generationIndex = 0;
  renderGeneration();
}

function toggleGenerationAuto() {
  if (generationTimer) {
    stopGenerationAuto();
    return;
  }

  elements.autoGenerateButton.textContent = "Pause Generation";
  generationTimer = window.setInterval(() => {
    if (generationIndex >= selectedContext.generationTokens.length) {
      stopGenerationAuto();
      return;
    }
    stepGeneration();
  }, 720);
}

function stopGenerationAuto() {
  if (generationTimer) {
    window.clearInterval(generationTimer);
    generationTimer = null;
  }
  elements.autoGenerateButton.textContent = "Auto Generate";
}

function revealHallucination() {
  elements.hallucinationDemo.hidden = false;
}

function renderHallucinationProbabilities() {
  elements.hallucinationProbabilities.innerHTML = hallucinationTokens
    .map(([token, value]) => probabilityRow(token, value))
    .join("");
}

function probabilityRow(token, value) {
  return `
    <div class="probability-row" data-token="${escapeHtml(token)}">
      <strong>${escapeHtml(token)}</strong>
      <span class="probability-track"><i class="probability-fill" style="--value:${value}"></i></span>
      <span>${value}%</span>
    </div>
  `;
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}
