function bindEvents() {
  window.addEventListener("scroll", () => {
    elements.header.dataset.elevated = String(window.scrollY > 6);
  });

  elements.prevButton.addEventListener("click", () => updateStation(currentStation - 1));
  elements.nextButton.addEventListener("click", () => updateStation(currentStation + 1));
  elements.restartTop.addEventListener("click", restartLab);
  elements.autoButton.addEventListener("click", toggleAutoWalkthrough);
  elements.termsToggle.addEventListener("click", toggleTerms);
  elements.termsClose.addEventListener("click", closeTerms);

  elements.tokenInput.addEventListener("input", () => {
    elements.rawText.textContent = elements.tokenInput.value || " ";
    elements.tokenNote.textContent = "Sentence edited. Tokenize again to see the new sequence.";
  });
  elements.tokenizeButton.addEventListener("click", () => tokenizeCurrentSentence(true));
  elements.restoreSentenceButton.addEventListener("click", () => {
    elements.tokenInput.value = tokenExamples.default;
    elements.rawText.textContent = tokenExamples.default;
    tokenizeCurrentSentence(true);
  });

  elements.capacitySlider.addEventListener("input", () => {
    renderContextTray();
    renderNetworkTokens();
  });

  elements.processButton.addEventListener("click", processNetwork);
  elements.temperatureSlider.addEventListener("input", renderProbabilities);
  elements.sampleButton.addEventListener("click", sampleNextToken);
  elements.resetPredictionButton.addEventListener("click", resetPrediction);
  elements.stepGenerateButton.addEventListener("click", stepGeneration);
  elements.autoGenerateButton.addEventListener("click", toggleGenerationAuto);
  elements.resetGenerationButton.addEventListener("click", resetGeneration);

  document.querySelectorAll("[data-truth]").forEach(button => {
    button.addEventListener("click", revealHallucination);
  });

  document.addEventListener("keydown", event => {
    if (event.key === "ArrowRight") updateStation(currentStation + 1);
    if (event.key === "ArrowLeft") updateStation(currentStation - 1);
    if (event.key === "Escape") closeTerms();
  });
}

